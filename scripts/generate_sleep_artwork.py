#!/usr/bin/env python3
"""Encode the Pocket Daily app's one-bit sleep artwork for the shared renderer."""

import argparse
import re
from itertools import groupby
from pathlib import Path
import subprocess

ARTWORK = ("woodcut", "observatory", "rail", "almanac")
PANELS = {"x3": (528, 792), "x4": (480, 800)}


def native_pixels(path, width, height):
    size = subprocess.check_output(["magick", "identify", "-format", "%w %h", str(path)], text=True)
    if size != f"{width} {height}":
        raise ValueError(f"{path} must be {width} × {height}")
    pixels = subprocess.check_output([
        "magick", str(path), "-background", "white", "-alpha", "remove",
        "-colorspace", "Gray", "-threshold", "50%", "-depth", "1", "gray:-",
    ])
    return pixels


def encode(pixels):
    encoded = bytearray()
    white = True
    for color, run in groupby((byte >> bit) & 1 for byte in pixels for bit in range(7, -1, -1)):
        if color != white:
            encoded.append(0)
        length = sum(1 for _ in run)
        while length >= 128:
            encoded.append((length & 127) | 128)
            length >>= 7
        encoded.append(length)
        white = not color
    return encoded


def write_gallery(root, catalog):
    # The Swift catalog is the persistent ID order. Native X4 rasters sample a
    # 400×624 master, so recover every master pixel from its first native pixel.
    source = (catalog.parent / "Studio/SleepArtwork.swift").read_text()
    gallery = source.split("private static let gallery:", 1)[1].split("    ]", 1)[0]
    names = re.findall(r'^        \("([a-z0-9]+)", ', gallery, re.MULTILINE)
    if len(names) != 76 or len(set(names)) != len(names):
        raise ValueError("Expected 76 unique gallery IDs")
    width, height = 400, 624
    native_width, native_height = PANELS["x4"]
    output = [
        "// Generated by scripts/generate_sleep_artwork.py from the Pocket Daily asset catalog.",
        "#pragma once", "", "namespace PocketDaily::Home::SleepArtwork {",
        f"inline constexpr int GalleryWidth = {width};",
        f"inline constexpr int GalleryHeight = {height};",
        "",
    ]
    for name in names:
        path = catalog / f"sleep-art-x4-gallery-{name}.imageset" / "artwork.png"
        pixels = native_pixels(path, native_width, native_height)
        master = bytearray(width * height // 8)
        for y in range(height):
            source_row = (y * native_height + height - 1) // height * (native_width // 8)
            for x in range(width):
                source_col = (x * native_width + width - 1) // width
                if pixels[source_row + source_col // 8] & (128 >> (source_col % 8)):
                    master[(y * width + x) // 8] |= 128 >> (x % 8)
        append_payload(output, f"gallery_{name}", encode(master))
    output.append("inline constexpr std::string_view Gallery[] = {")
    for name in names:
        output.append(f"    std::string_view(gallery_{name}, sizeof(gallery_{name}) - 1),")
    output.extend(["};", "", "}  // namespace PocketDaily::Home::SleepArtwork", ""])
    (root / "src/pocket_daily/home/SleepArtworkGalleryData.h").write_text("\n".join(output))


def append_payload(output, name, payload):
    output.append(f"inline constexpr char {name}[] =")
    for offset in range(0, len(payload), 24):
        escapes = "".join(f"\\x{byte:02x}" for byte in payload[offset:offset + 24])
        output.append(f'    "{escapes}"')
    output[-1] += ";"
    output.append("")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("asset_catalog", type=Path)
    args = parser.parse_args()
    output = [
        "// Generated by scripts/generate_sleep_artwork.py from the Pocket Daily asset catalog.",
        "#pragma once", "", "namespace PocketDaily::Home::SleepArtwork {",
        "",
    ]
    for model, (width, height) in PANELS.items():
        for artwork in ARTWORK:
            path = args.asset_catalog / f"sleep-art-{model}-{artwork}.imageset" / "artwork.png"
            payload = encode(native_pixels(path, width, height))
            append_payload(output, f"{artwork}_{model}", payload)
        names = [f"std::string_view({name}_{model}, sizeof({name}_{model}) - 1)" for name in ARTWORK]
        output.extend([
            f"inline constexpr Panel {model}{{",
            f"    {width},",
            f"    {height},",
            f"    {{{names[0]}, {names[1]},",
            f"     {names[2]}, {names[3]}}}}};",
        ])
        output.append("")
    output.append("}  // namespace PocketDaily::Home::SleepArtwork\n")
    root = Path(__file__).resolve().parents[1]
    (root / "src/pocket_daily/home/SleepArtworkData.h").write_text("\n".join(output))
    write_gallery(root, args.asset_catalog)


if __name__ == "__main__":
    main()
